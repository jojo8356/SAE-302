<h1>Confidentialité</h1>

<h2>Quelles données sont enregistrées ?</h2>
<p>Pour faire fonctionner la boutique, MiniShop enregistre uniquement ce que
vous saisissez : vos nom, prénom et e-mail, vos coordonnées de livraison
(rue, code postal, ville), et l'historique de vos commandes. Aucune donnée
bancaire n'est collectée : le paiement est simulé.</p>

<h2>Comment votre mot de passe est-il protégé ?</h2>
<p>Il n'est jamais stocké en clair : seule une empreinte irréversible
(hachage) est conservée, de sorte que même la base de données ne permet pas
de retrouver votre mot de passe.</p>

<h2>Combien de temps sont-elles conservées ?</h2>
<p>Les données de votre compte sont conservées <strong>36 mois</strong> après
votre dernier contact, puis le compte peut être fermé. L'historique des
commandes est tracé à des fins de suivi (qui a fait quoi, et quand).</p>

<h2>Vos droits</h2>
<p>Vous pouvez consulter et corriger vos informations à tout moment depuis
<a href="/compte">Mon compte</a>, et y changer votre mot de passe. Sur cette
maquette pédagogique, c'est la seule voie de demande : il n'y a ni
formulaire de contact ni service client derrière le site (voir la page
<a href="/contact">Contact</a>) — utilisez donc des informations fictives.</p>

<p><small>MiniShop est une maquette pédagogique réalisée par des étudiants :
utilisez des informations fictives, comme les comptes de démonstration
fournis. Aucune donnée n'est transmise à des tiers ni utilisée à des fins
publicitaires.</small></p>
