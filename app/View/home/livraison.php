<h1>Livraison</h1>

<h2>Frais de port</h2>
<ul>
    <li>Livraison standard : <strong>4,90&nbsp;€ TTC</strong> par commande.</li>
    <li><strong>Offerte dès 80,00&nbsp;€</strong> de marchandises.</li>
</ul>
<p>Le montant des frais de port est calculé sur le total de votre panier et
affiché <strong>avant la validation</strong> de la commande (article L221-5 du
code de la consommation). Une fois la commande validée, ce montant est
<strong>figé</strong> : une évolution ultérieure des tarifs ne retouche jamais
une commande passée.</p>

<h2>Adresse de livraison</h2>
<p>L'adresse proposée à la validation est celle de votre profil (rue, code
postal et ville) ; vous pouvez la corriger pour la commande en cours avant de
confirmer. C'est cette adresse, telle que vous l'avez confirmée, qui est
enregistrée avec la commande et visible sur son détail.</p>

<h2>Suivi de l'expédition</h2>
<p>Après validation, suivez l'avancement depuis
<a href="/mes-commandes">Mes commandes</a> : préparation, expédition, puis
livraison. Tant que la commande n'est pas expédiée, vous pouvez encore
l'<a href="/retractation">annuler</a> depuis son détail.</p>

<p><small>MiniShop est une maquette pédagogique : aucun colis réel n'est
expédié et aucun transporteur n'intervient ; les statuts illustrent le
parcours d'une commande.</small></p>
