<h1>Rétractation</h1>

<h2>Votre droit</h2>
<p>Pour tout achat à distance, vous disposez d'un délai de
<strong>14 jours</strong> à compter de la réception de votre commande pour
changer d'avis, sans avoir à vous justifier (articles L221-18 et suivants du
code de la consommation).</p>

<h2>Concrètement, sur MiniShop</h2>
<p>Tant que votre commande n'a pas été <strong>expédiée</strong>, l'annulation
est immédiate et gratuite :</p>
<ol>
    <li>Connectez-vous et ouvrez <a href="/mes-commandes">Mes commandes</a> ;</li>
    <li>ouvrez le détail de la commande concernée ;</li>
    <li>cliquez sur « Annuler cette commande » et confirmez.</li>
</ol>
<p>Le stock des articles est alors restitué automatiquement et le montant
total de la commande (frais de port compris) est soldé : rien ne vous est
dû. Une confirmation vous est toujours demandée avant cette action
définitive.</p>

<h2>Et après l'expédition ?</h2>
<p>Une commande expédiée ne peut plus être annulée depuis le site. MiniShop
étant une maquette pédagogique (paiement simulé, aucun colis réel), aucun
retour de marchandise n'est traité ; dans une boutique réelle, les frais de
renvoi resteraient à votre charge, sauf mention contraire du vendeur. Le
cadre complet est décrit à l'article 4 des
<a href="/cgv">Conditions générales de vente</a>.</p>
